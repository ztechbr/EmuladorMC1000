"""Top-level, base, CB, and ED opcode dispatch."""
class DispatchMixin:
    def decode_and_execute(self):
        opcode=self._fetch_byte()
        if opcode==0xcb:return self._execute_cb(self._fetch_byte())
        if opcode==0xed:return self._execute_ed(self._fetch_byte())
        if opcode in (0xdd,0xfd):return self._execute_index(opcode,self._fetch_byte())
        return self._execute_main(opcode)
    def _execute_cb(self,s):
        if s<=0x3f:return self._op_rot(s)
        if s<=0x7f:return self._op_bit(s)
        if s<=0xbf:return self._op_res(s)
        return self._op_set(s)
    def _execute_main(self,op):
        if op in (0x00,0x01,0x08,0x10,0x11,0x31):return self._op_prefix_ignored_basic(op)
        if op==0x76:return self._op_halt()
        if 0x40<=op<=0x7f and op!=0x76:return self._op_ld_r_r(op)
        if op in (0x06,0x0e,0x16,0x1e,0x26,0x2e,0x36,0x3e):return self._op_ld_r_n(op)
        if op in (0x0a,0x1a):return self._op_ld_a_irr(self._bc() if op==0x0a else self._de())
        if op in (0x02,0x12):return self._op_ld_irr_a(self._bc() if op==0x02 else self._de())
        if op==0x3a:return self._op_ld_a_inn()
        if op==0x32:return self._op_ld_inn_a()
        if op==0x21:return self._op_ld_hl_nn()
        if op in (0x37,0x3f):return self._op_scf_ccf(op,prefixed=False)
        if op==0x22:return self._op_ld_nn_hl()
        if op==0x2a:return self._op_ld_hl_nn_from_mem()
        if op==0xdb:return self._op_in_a_n()
        if op==0xd3:return self._op_out_n_a()
        if 0x80<=op<=0xbf:return self._op_alu_r(op)
        if op in (0xc6,0xce,0xd6,0xde,0xe6,0xee,0xf6,0xfe):return self._op_alu_n(op)
        if op in (0x04,0x0c,0x14,0x1c,0x24,0x2c,0x3c):return self._op_inc_r(op)
        if op in (0x05,0x0d,0x15,0x1d,0x25,0x2d,0x3d):return self._op_dec_r(op)
        if op==0x34:return self._op_inc_hl()
        if op==0x35:return self._op_dec_hl()
        if op==0x27:return self._op_daa()
        if op==0x2f:return self._op_cpl()
        if op==0x07:return self._op_rlca()
        if op==0x0f:return self._op_rrca()
        if op==0x17:return self._op_rla()
        if op==0x1f:return self._op_rra()
        if op in (0x09,0x19,0x29,0x39):return self._op_add_hl_rr(op)
        if op in (0x03,0x13,0x23,0x33):return self._op_inc_rr(op)
        if op in (0x0b,0x1b,0x2b,0x3b):return self._op_dec_rr(op)
        if op in (0x18,0x20,0x28,0x30,0x38):return self._op_jr(op)
        if op in (0xc0,0xc8,0xd0,0xd8,0xe0,0xe8,0xf0,0xf8):return self._op_ret_cc(op)
        if op==0xc9:return self._op_ret()
        if op in (0xc2,0xca,0xd2,0xda,0xe2,0xea,0xf2,0xfa,0xc3):return self._op_jp(op)
        if op in (0xc4,0xcc,0xd4,0xdc,0xe4,0xec,0xf4,0xfc,0xcd):return self._op_call(op)
        if op in (0xc7,0xcf,0xd7,0xdf,0xe7,0xef,0xf7,0xff):return self._op_rst(op)
        if op in (0xc1,0xd1,0xe1):return self._op_pop_rr(op)
        if op in (0xc5,0xd5,0xe5):return self._op_push_rr(op)
        if op==0xf1:return self._op_pop_af()
        if op==0xf5:return self._op_push_af()
        if op==0xf9:return self._op_ld_sp_hl()
        if op==0xd9:return self._op_exx()
        if op==0xe3:return self._op_ex_sp_hl()
        if op==0xe9:return self._op_jp_hl()
        if op==0xeb:return self._op_ex_de_hl()
        if op==0xf3:return self._op_interrupt_enable(False)
        if op==0xfb:return self._op_interrupt_enable(True)
        raise NotImplementedError(f'unhandled opcode 0x{op:02X} at PC 0x{(self.pc-1)&0xffff:04X}')
    def _execute_ed(self,op):
        table={0x47:self._op_ld_i_a,0x4f:self._op_ld_r_a,0x57:self._op_ld_a_i,0x5f:self._op_ld_a_r,0x67:self._op_rrd,0x6f:self._op_rld,0x77:self._op_ed_nop,0x7f:self._op_ed_nop,0xa0:self._op_ldi,0xa1:self._op_cpi,0xa2:self._op_ini,0xa3:self._op_outi,0xa8:self._op_ldd,0xa9:self._op_cpd,0xaa:self._op_ind,0xab:self._op_outd,0xb0:self._op_ldir,0xb1:self._op_cpir,0xb2:self._op_inir,0xb3:self._op_otir,0xb8:self._op_lddr,0xb9:self._op_cpdr,0xba:self._op_indr,0xbb:self._op_otdr}
        if op in table:return table[op]()
        if op in (0x45,0x55,0x65,0x75):return self._op_retn()
        if op in (0x4d,0x5d,0x6d,0x7d):return self._op_reti()
        if op in (0x4a,0x5a,0x6a,0x7a):return self._op_adc_hl_rr(op)
        if op in (0x42,0x52,0x62,0x72):return self._op_sbc_hl_rr(op)
        if op in (0x43,0x53,0x63,0x73):return self._op_ld_nn_rr((op>>4)&3)
        if op in (0x4b,0x5b,0x6b,0x7b):return self._op_ld_rr_nn_from_mem((op>>4)&3)
        if op in (0x46,0x4e,0x66,0x6e):return self._op_im(0)
        if op in (0x56,0x76):return self._op_im(1)
        if op in (0x5e,0x7e):return self._op_im(2)
        if op in (0x44,0x4c,0x54,0x5c,0x64,0x6c,0x74,0x7c):return self._op_neg()
        if 0x40<=op<=0x78 and (op&7)==0:return self._op_in_r_c(op)
        if 0x41<=op<=0x79 and (op&7)==1:return self._op_out_c_r(op)
        raise NotImplementedError(f'unhandled ED opcode 0x{op:02X} at PC 0x{(self.pc-2)&0xffff:04X}')
